# dequantized values the readers must return for random_values() quantized
# at 8 / 16 / 32 bits; float arithmetic as the writers do it, in float64:
# code = round_half_even((v - min) / scale * top), value = code / top * scale + min,
# then rounded once to float32 (struct)
def _random_dequantized(bits):
    vals = random_values()
    lo, hi = min(vals), max(vals)
    scale = hi - lo
    if scale < 1e-10:
        scale = 1.0
    top = float(2 ** bits - 1)
    out = []
    for v in vals:
        code = min(max(round((v - lo) / scale * top), 0), 2 ** bits - 1)
        out.append(struct.unpack("<I", struct.pack("<f", code / top * scale + lo))[0])
    return out


with open(HERE / "quantized_expected.txt", "a") as f:
    for _bits in (8, 16, 32):
        f.write(f"rand{_bits} | " + " ".join(f"{b:08x}" for b in _random_dequantized(_bits)) + "\n")


# ---------------------------------------------------------------------------
# reconstruct: original = generated (float64) + residual (float32), in
# float64, then the original's dtype. Integers: NaN is refused; otherwise
# rounded half to even and saturated to the dtype's range in the integer
# domain (inf saturates too). Floats: rounded once to the dtype (an overflow
# is an infinity). Computed with Python floats, ints and struct only.
INTS = {"int8": (8, True), "int16": (16, True), "int32": (32, True), "int64": (64, True),
        "uint8": (8, False), "uint16": (16, False), "uint32": (32, False), "uint64": (64, False)}
FLOATS = {"float16": "<e", "float32": "<f", "float64": "<d"}


def _f32(v):
    return struct.unpack("<f", struct.pack("<f", v))[0]


def _expected(dtype, s):
    if dtype in INTS:
        bits, signed = INTS[dtype]
        if s != s:
            return "error"
        lo, hi = (-(2 ** (bits - 1)), 2 ** (bits - 1) - 1) if signed else (0, 2 ** bits - 1)
        n = hi if s == float("inf") else lo if s == -float("inf") else round(s)
        n = min(max(n, lo), hi)
        return n.to_bytes(bits // 8, "little", signed=signed).hex()
    try:
        return struct.pack(FLOATS[dtype], s).hex()
    except OverflowError:
        return struct.pack(FLOATS[dtype], float("inf") if s > 0 else -float("inf")).hex()


def _vectors(dtype):
    inf, nan = float("inf"), float("nan")
    pairs = [(0.0, 0.0), (10.0, 0.5), (11.0, 0.5), (-10.0, -0.5), (-11.0, -0.5),
             (2.0, 0.25), (100.0, -36.54), (inf, 0.0), (-inf, 0.0), (nan, 0.0), (1.0, nan)]
    if dtype in INTS:
        bits, signed = INTS[dtype]
        lo, hi = (-(2 ** (bits - 1)), 2 ** (bits - 1) - 1) if signed else (0, 2 ** bits - 1)
        fhi, flo = float(hi), float(lo)
        below = math.nextafter(fhi, -inf) if fhi > hi else fhi
        for g in (fhi, below, fhi + 1.0, math.nextafter(fhi, inf), flo, flo - 1.0,
                  math.nextafter(flo, -inf), flo - 0.5, flo + 0.5, fhi - 0.5, fhi + 0.5,
                  float(hi // 2), -1.0, -0.5):
            pairs.append((g, 0.0))
        pairs.append((fhi - 1.0, 0.75))
    else:
        for g in (65504.0, 65519.99, 65520.0, 2.0 ** -25, 3 * 2.0 ** -25, 2.0 ** -24 * 0.75,
                  1e-8, 3.4028234663852886e38, 3.4028235677973366e38, 1e300, -1e300,
                  1.0 + 2.0 ** -11, 1.0 + 3 * 2.0 ** -11, 1.0 + 2.0 ** -24, 1.0 + 3 * 2.0 ** -24,
                  # around the smallest normal half 2^-14 (subnormal below it)
                  3 * 2.0 ** -16, 1.5 * 2.0 ** -15, 2.0 ** -14 - 2.0 ** -25, 2.0 ** -14 - 2.0 ** -23,
                  2.0 ** -14, 2.0 ** -14 + 2.0 ** -25):
            pairs.append((g, 0.0))
    bit_pairs = [(struct.unpack("<Q", struct.pack("<d", g))[0],
                  struct.unpack("<I", struct.pack("<f", _f32(r)))[0]) for g, r in pairs]
    # NaNs with payloads, signaling NaNs, negative NaNs, a NaN on each side and
    # on both, and inf + -inf (whose NaN the hardware gives differently)
    one, inf_b, ninf_b = 0x3FF0000000000000, 0x7FF0000000000000, 0xFFF0000000000000
    bit_pairs += [(0x7FF4000000000000, 0), (0x7FFFFFFFFFFFFFFF, 0), (0xFFF0040000000000, 0),
                  (0x7FF0000000000001, 0), (0x7FF0040000000000, 0), (0xFFF8000000000123, 0),
                  (one, 0x7F800001), (one, 0xFFC12345), (one, 0x7FFFFFFF), (one, 0xFF800001),
                  (0x7FF4000000000000, 0xFFC00001), (0x7FF8000000000001, 0x7F800001),
                  (inf_b, 0xFF800000), (ninf_b, 0x7F800000)]
    rows = []
    for gb, rb in bit_pairs:
        rows.append(f"{dtype} {gb:016x} {rb:08x} {_expected_bits(dtype, gb, rb)}")
    return rows


# The NaN of generated + residual, chosen by rule rather than by the
# hardware (which differs in which NaN it keeps and in the sign of the NaN of
# inf + -inf): generated's NaN with the quiet bit set; else the residual's NaN
# widened (sign, quiet bit, its 23 payload bits as the top of the 52); else
# (inf + -inf) the positive quiet NaN 0x7FF8000000000000
def _sum_nan_bits(gb, rb):
    g_nan = (gb >> 52) & 0x7FF == 0x7FF and gb & (2 ** 52 - 1)
    r_nan = (rb >> 23) & 0xFF == 0xFF and rb & (2 ** 23 - 1)
    if g_nan:
        return gb | 1 << 51
    if r_nan:
        return (rb >> 31) << 63 | 0x7FF8000000000000 | (rb & 0x7FFFFF) << 29
    return None


def _expected_bits(dtype, gb, rb):
    nan_bits = _sum_nan_bits(gb, rb)
    g = struct.unpack("<d", struct.pack("<Q", gb))[0]
    r = struct.unpack("<f", struct.pack("<I", rb))[0] if nan_bits is None else 0.0
    if nan_bits is None and abs(g) == float("inf") and abs(r) == float("inf") and g != r:
        nan_bits = 0x7FF8000000000000
    if nan_bits is None:
        return _expected(dtype, g + r)
    if dtype in INTS:
        return "error"
    # a NaN keeps its sign, the quiet bit and the top of its payload
    sign = nan_bits >> 63
    if dtype == "float16":
        return (sign << 15 | 0x7E00 | (nan_bits >> 42) & 0x3FF).to_bytes(2, "little").hex()
    if dtype == "float32":
        return (sign << 31 | 0x7FC00000 | (nan_bits >> 29) & 0x3FFFFF).to_bytes(4, "little").hex()
    return nan_bits.to_bytes(8, "little").hex()


