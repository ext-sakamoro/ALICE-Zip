# Random-valued residuals for the quantized fixtures of both writers
import sys  # noqa: E402

sys.path.insert(0, str(HERE))
from residual_values import random_values  # noqa: E402


# dequantized values the readers must return for random_values() quantized
# at 8 / 16 / 32 bits; float arithmetic as the writers do it, in float64:
# code = round_half_even((v - min) / scale * top), value = code / top * scale + min,
# then rounded once to float32 (struct)
def _random_dequantized(bits):
    vals = random_values()
    lo, hi = min(vals), max(vals)
    scale = hi - lo
    if scale < 1e-10:
        scale = 1.0
    top = float(2 ** bits - 1)
    out = []
    for v in vals:
        code = min(max(round((v - lo) / scale * top), 0), 2 ** bits - 1)
        out.append(struct.unpack("<I", struct.pack("<f", code / top * scale + lo))[0])
    return out


with open(HERE / "quantized_expected.txt", "a") as f:
    for _bits in (8, 16, 32):
        f.write(f"rand{_bits} | " + " ".join(f"{b:08x}" for b in _random_dequantized(_bits)) + "\n")


