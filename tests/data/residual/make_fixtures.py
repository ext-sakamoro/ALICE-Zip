# ---------------------------------------------------------------------------
# Lossless writing from the original (exceptions). Shared inputs of both
# writers: exception_cases.txt, rows `dtype original generated` with the
# original as little-endian hex of the dtype and generated as float64 bits.
# Specials (NaN payloads, signaling NaNs, infinities, -0, subnormals, the
# extremes), values from a linear congruential sequence, and generated values
# near the original, NaN, infinite or far away.
def _lcg(seed):
    x = seed
    while True:
        x = (x * 6364136223846793005 + 1442695040888963407) % 2 ** 64
        yield x


_FLOAT_SPECIALS = {
    2: [0x7E01, 0x7C01, 0x7C00, 0xFC00, 0x8000, 0x0001, 0x7BFF, 0xFE00],
    4: [0x7FC00001, 0x7F800001, 0x7F800000, 0xFF800000, 0x80000000, 0x00000001,
        0x7F7FFFFF, 0xFFC12345],
    8: [0x7FF8000000000001, 0x7FF0000000000001, 0x7FF0000000000000, 0xFFF0000000000000,
        0x8000000000000000, 0x0000000000000001, 0x7FEFFFFFFFFFFFFF, 0xFFF8000000012345],
}
_GEN_KINDS = ["near", "near", "nan", "inf", "-inf", "snan", "far", "near", "near", "exact"]


def _value_of(dtype, raw):
    if dtype in FLOATS:
        return struct.unpack(FLOATS[dtype], raw)[0]
    bits, signed = INTS[dtype]
    return float(int.from_bytes(raw, "little", signed=signed))


def _generated(kind, value):
    if kind == "nan":
        return 0x7FF8000000000123
    if kind == "snan":
        return 0x7FF0000000000001
    if kind in ("inf", "-inf"):
        return 0x7FF0000000000000 if kind == "inf" else 0xFFF0000000000000
    finite = value == value and abs(value) != float("inf")
    if kind == "far":
        g = 1e30
    elif kind == "exact":
        g = value if finite else 2.0
    else:
        g = value + 0.375 if finite else 2.0
    return struct.unpack("<Q", struct.pack("<d", g))[0]


def exception_cases():
    rows = []
    rng = _lcg(0x9E3779B97F4A7C15)
    for dtype in ["float16", "float32", "float64", "int8", "int16", "int32", "int64",
                  "uint8", "uint16", "uint32", "uint64"]:
        if dtype in FLOATS:
            width = struct.calcsize(FLOATS[dtype])
            originals = [b.to_bytes(width, "little") for b in _FLOAT_SPECIALS[width]]
            originals += [(next(rng) % 2 ** (8 * width)).to_bytes(width, "little") for _ in range(16)]
        else:
            bits, signed = INTS[dtype]
            width = bits // 8
            lo, hi = (-(2 ** (bits - 1)), 2 ** (bits - 1) - 1) if signed else (0, 2 ** bits - 1)
            ints = [lo, hi, 0, lo + 1, hi - 1, 1]
            ints += [lo + next(rng) % (hi - lo + 1) for _ in range(18)]
            originals = [n.to_bytes(width, "little", signed=signed) for n in ints]
        for i, raw in enumerate(originals):
            g = _generated(_GEN_KINDS[i % len(_GEN_KINDS)], _value_of(dtype, raw))
            rows.append(f"{dtype} {raw.hex()} {g:016x}")
    return rows


with open(HERE / "exception_cases.txt", "w") as f:
    f.write("# dtype | original (little-endian bytes of the dtype) | generated (float64 bits)\n"
            "# shared input of both lossless writers (generated by make_fixtures.py)\n")
    for _row in exception_cases():
        f.write(_row + "\n")


# files with exceptions that both readers refuse (method none, 4 values,
# exception block = positions (u64) then the original elements)
def _exc(name, header_extra, positions, elements=None, version=3, residual=None):
    header = {"method": "none", "shape": [4], "dtype": "float32", "quant_bits": None,
              "version": version, **header_extra}
    residual = residual if residual is not None else [5.0, 0.0, 6.0, 4.0]
    elements = elements if elements is not None else [b"\x00\x00\xc0\x7f"] * len(positions)
    block = b"".join(struct.pack("<Q", p) for p in positions) + b"".join(elements)
    _write(name, header, struct.pack("<4f", *residual) + block)


